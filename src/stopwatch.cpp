unsigned long startTime = 0;
unsigned long elapsedTime = 0;

bool running = false;

void startStopWatch() {
    running = true;
    startTime = millis() - elapsedTime;
}

void pauseStopwatch() {
    elapsedTime = millis() - startTime;
    running = false;
}

void resetStopwatch() {
    elapsedTime = 0;
    startTime = millis() - elapsedTime;
}

extern int afkTime;

void Stopwatch() {
    afkTime = 0;
    if(rightButtonTap()) {
        if(running) {
            pauseStopwatch();
        } else {
            startStopWatch();
        }
    }
    if(leftButtonTap()) {
        resetStopwatch();
    }
    
    if(running) {
        elapsedTime = millis() - startTime;
    }

    u8g2.clearBuffer();
    u8g2.setFontMode(1);
    u8g2.setBitmapMode(1);

    // Layer 1
    String ms = String((elapsedTime % 1000)/10);
    unsigned long totalSeconds = elapsedTime / 1000;
    String hours = String((totalSeconds / 3600) % 100);
    String seconds = String(totalSeconds % 60);
    String minutes = String((totalSeconds / 60) % 60);
    String combinedTime;
    if(elapsedTime > 3600000){
        combinedTime = (hours.length() < 2 ? "0" + hours : hours) + ":" + (minutes.length() < 2 ? "0" + minutes : minutes) + ":" + (seconds.length() < 2 ? "0" + seconds : seconds);
    }else{
        combinedTime = (minutes.length() < 2 ? "0" + minutes : minutes) + ":" + (seconds.length() < 2 ? "0" + seconds : seconds) + "." + (ms.length() == 1 ? "0" + ms : ms);
    }

    u8g2.setFont(u8g2_font_profont22_tr);
    u8g2.drawStr(17, 26, combinedTime.c_str());

    // Layer 2
    u8g2.drawFrame(7, 6, 113, 27);

    if(running){
        u8g2.drawXBMP(77, 38, 19, 20, image_unpaused_bits);
    }else{
        u8g2.drawXBMP(77, 38, 19, 20, image_paused_1_bits);
    }
    // unreset
    u8g2.drawXBMP(31, 38, 19, 20, image_unreset_bits);

    // download
    u8g2.drawXBMP(109, 44, 4, 7, image_download_bits);

    // download
    u8g2.drawXBMP(14, 44, 4, 7, image_download_1_bits);

    u8g2.sendBuffer();
}
