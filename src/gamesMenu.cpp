int Blink = 0;
int BlinkDelay = 16;

int gameIndex = 0;
int gameMode = 0;

void gamesMenu(int reset = 0) {

    if(reset == 1){
        gameMode = 0;
        return;
    }

    if(rightButtonTap()){
        gameMode = 1;
    }

    if(gameMode){
        switch (gameIndex)
        {
        case 0:
            Dino();
            return;
            break;
        
        default:
            break;
        }
    }
    

    Blink = (Blink + 1) % BlinkDelay;
    u8g2.clearBuffer();
    u8g2.setFontMode(1);
    u8g2.setBitmapMode(1);
    // iconBorder
    u8g2.drawXBMP(63, 3, 62, 58, image_iconBorder_bits);

    // Layer 2
    u8g2.setFont(u8g2_font_6x13O_tr);
    u8g2.drawStr(4, 14, "CHROME");

    // Layer 2 copy
    u8g2.drawStr(4, 28, "DINO");

    // Layer 4
    u8g2.setFont(u8g2_font_5x8_tr);
    u8g2.drawStr(11, 61, "6/7");

    // Layer 5
    u8g2.setFont(u8g2_font_profont11_tr);
    u8g2.drawStr(6, 45, "START");

    // arrowRight
    u8g2.drawXBMP(38, 39, 3, 5, image_arrowRight_bits);

    if(Blink < BlinkDelay/2){
        // select
        u8g2.drawXBMP(4, 35, 40, 13, image_select_bits);
    }

    // arrows
    u8g2.drawXBMP(4, 56, 29, 4, image_arrows_bits);
    

    u8g2.sendBuffer();
}
